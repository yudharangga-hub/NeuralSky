# ==============================================================================
# ENGINE PLOTTING
# ==============================================================================
def generate_plot(data):
    epochs_range = range(len(data['train_acc']))
    plt.figure(figsize=(12, 4))
    
    # 1. Plot Accuracy
    plt.subplot(1, 2, 1)
    plt.plot(epochs_range, data['train_acc'], label='Training Accuracy')
    plt.plot(epochs_range, data['val_acc'], label='Validation Accuracy')
    plt.title(f"{data['name']} Accuracy")
    plt.xlabel('Epochs')
    plt.ylabel('Accuracy')
    plt.legend(loc='lower right')
    plt.grid(True, alpha=0.3)
    
    # 2. Plot Loss
    plt.subplot(1, 2, 2)
    plt.plot(epochs_range, data['train_loss'], label='Training Loss')
    plt.plot(epochs_range, data['val_loss'], label='Validation Loss')
    plt.title(f"{data['name']} Loss")
    plt.xlabel('Epochs')
    plt.ylabel('Loss')
    plt.legend(loc='upper right')
    plt.grid(True, alpha=0.3)
    
    # Simpan
    save_path = os.path.join(HISTORY_SAVE_PATH, data['file'])
    plt.savefig(save_path)
    plt.close()
    print(f"[SUKSES] Grafik {data['name']} tersimpan di: {save_path}")

